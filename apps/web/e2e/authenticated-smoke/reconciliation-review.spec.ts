import { expect, test } from "@playwright/test";

test("reconciliation reviews ambiguous matches, pages and searches without changing the source scope", async ({ page }, testInfo) => {
  const offset = { desktop: 0, tablet: 100, phone: 200 }[testInfo.project.name];
  expect(offset).toBeDefined();
  const sessionId = `a00002f0-0000-4000-8000-${String(offset! + 2).padStart(12, "0")}`;
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(process.env.E2E_USER_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.E2E_USER_PASSWORD!);
  await page.getByRole("button", { name: "Iniciar sesión", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard(?:\?|$)/, { timeout: 30_000 });
  await page.goto(`/tesoreria/conciliacion/${sessionId}`);
  const lines = page.getByRole("region", { name: "Líneas del extracto", exact: true });
  const movements = page.getByRole("region", { name: "Revisar coincidencias", exact: true });
  await expect(lines.getByRole("button", { name: "Pendientes (12)", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(lines.locator("li")).toHaveCount(10);
  await lines.getByRole("button", { name: "Siguiente", exact: true }).click();
  await expect(lines.locator("li")).toHaveCount(2);
  await expect(lines.getByText("Página 2 de 2", { exact: false })).toBeVisible();
  await lines.getByLabel("Buscar en el extracto").fill("REV-ALFA");
  await expect(lines.locator("li")).toHaveCount(1);
  await lines.getByRole("button", { name: /Transferencia para revisar/ }).click();
  await expect(movements.getByRole("status")).toContainText("2 coincidencias posibles");
  await expect(movements.getByRole("button", { name: "Emparejar seleccionados" })).toHaveCount(0);
  await movements.getByRole("button", { name: /Cobranza revisión Alfa/ }).click();
  await expect(movements.getByRole("region", { name: "Par a confirmar" })).toContainText("Cobranza revisión Alfa");
  // A new search must clear the previous selection; a hidden candidate cannot be confirmed.
  await movements.getByLabel("Buscar movimiento").fill("Beta");
  await expect(movements.getByRole("region", { name: "Par a confirmar" })).toHaveCount(0);
  await expect(movements.getByRole("button", { name: /Cobranza revisión Alfa/ })).toHaveCount(0);
  await expect(movements.getByRole("status")).toContainText("2 coincidencias posibles");
  await movements.getByLabel("Buscar movimiento").fill("");
  await movements.getByRole("button", { name: /Cobranza revisión Alfa/ }).click();
  const layout = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, document: document.documentElement.scrollWidth }));
  expect(layout.document).toBeLessThanOrEqual(layout.viewport + 1);
  for (const button of await movements.getByRole("button").all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await testInfo.attach("reconciliation-pair-review", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });
  await movements.getByRole("button", { name: "Emparejar seleccionados", exact: true }).click();
  await expect(lines.getByRole("button", { name: "Pendientes (11)", exact: true })).toBeVisible();
  await expect(lines.getByRole("button", { name: /Transferencia para revisar/ })).toHaveCount(0);
  await lines.getByRole("button", { name: "Todas (12)", exact: true }).click();
  await expect(lines.getByText(/Emparejado: Cobranza revisión Alfa/)).toBeVisible();
  await lines.getByRole("button", { name: "Desconciliar", exact: true }).click();
  await expect(lines.getByRole("button", { name: "Pendientes (12)", exact: true })).toBeVisible();
  await lines.getByRole("button", { name: /Transferencia para revisar/ }).click();
  await expect(movements.getByRole("status")).toContainText("2 coincidencias posibles");
  await lines.getByLabel("Buscar en el extracto").fill("REV-11");
  await lines.getByRole("button", { name: /Línea de revisión 11/ }).click();
  await expect(movements.getByRole("status")).toContainText("No hay movimientos confirmados");
  await expect(movements.getByRole("button", { name: "Emparejar seleccionados" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Cerrar conciliación", exact: true })).toBeDisabled();
});
